-- Stock Manager's tables in the portal database: an exact copy of the live Auto Stock Manager's tables (no data),
-- generated from the live database with pg_dump --schema-only and "public" renamed to "stock".
-- NOT in supabase/migrations on purpose: run it by hand, once, when switching over. The tables that were there before
-- are kept, renamed to stock_before_full_copy. The portal's older stock pages stop working once this has run.
begin;
create extension if not exists citext with schema public;
do $$ begin
  if exists (select 1 from pg_namespace where nspname = 'stock_before_full_copy') then
    raise exception 'stock_before_full_copy already exists: this file has been run before';
  end if;
  if exists (select 1 from pg_namespace where nspname = 'stock') then
    alter schema stock rename to stock_before_full_copy;
  end if;
end $$;
create schema stock;

