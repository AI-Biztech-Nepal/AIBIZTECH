"""Turn a pg_dump -s of a legacy app's `public` schema into an additive portal migration.

usage: build_schema.py <finance|attendance> <schema-dump.sql> <out.sql>
Only creates; never drops. Helpers are rewired to core (see HELPERS)."""
import re, sys

svc, src, out = sys.argv[1:4]
DROP = re.compile(r"^(\\|ALTER .* OWNER TO |GRANT |REVOKE |SET |SELECT pg_catalog\.set_config|CREATE SCHEMA |COMMENT ON SCHEMA |CREATE EXTENSION |COMMENT ON EXTENSION |ALTER DEFAULT PRIVILEGES|CREATE PUBLICATION|ALTER PUBLICATION)")
HELPERS = {
  "attendance": """
-- Tenant = active org that has the attendance service; role = service role in that org.
create or replace function attendance.my_company_id() returns uuid language sql stable security definer set search_path = '' as $$
  select p.active_org_id from core.profiles p
  where p.user_id = auth.uid()
    and exists (select 1 from core.service_roles r where r.org_id = p.active_org_id and r.user_id = p.user_id and r.service_key = 'attendance')
$$;
create or replace function attendance.is_admin() returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from core.service_roles r where r.org_id = attendance.my_company_id() and r.user_id = auth.uid() and r.service_key = 'attendance' and r.role = 'admin')
$$;
create or replace function attendance.is_admin_or_hr() returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from core.service_roles r where r.org_id = attendance.my_company_id() and r.user_id = auth.uid() and r.service_key = 'attendance' and r.role in ('admin','hr'))
$$;
""",
  "finance": """
-- Owner = active org that has the finance service (owner_id columns now hold org ids).
create or replace function finance.finance_current_owner() returns uuid language sql stable security definer set search_path = '' as $$
  select p.active_org_id from core.profiles p
  where p.user_id = auth.uid()
    and exists (select 1 from core.service_roles r where r.org_id = p.active_org_id and r.user_id = p.user_id and r.service_key = 'finance')
$$;
""",
}
lines = [l for l in open(src, encoding="utf8").read().replace("\r", "").split("\n") if not DROP.match(l)]
sql = "\n".join(lines)
sql = sql.replace("public.", f"{svc}.").replace("SET search_path TO 'public'", f"SET search_path TO '{svc}'")
sql = re.sub(r"\n{3,}", "\n\n", sql)
# the tenant column now holds an org id, not a user id
sql = sql.replace("FOREIGN KEY (owner_id) REFERENCES auth.users(id)", "FOREIGN KEY (owner_id) REFERENCES core.organizations(id)")
body = f"""-- {svc}: legacy app schema moved into the portal DB. Generated by scripts/migrate/build_schema.py. Additive only.
set check_function_bodies = off;  -- dump orders functions before the tables they read
create schema if not exists {svc};
{sql}
{HELPERS[svc]}
-- functions that referenced tables unqualified keep working
do $$ declare f record; begin
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = '{svc}' and p.proconfig is null and p.prokind = 'f' loop
    execute format('alter function %s set search_path = {svc}, extensions, public', f.sig);
  end loop; end $$;
grant usage on schema {svc} to authenticated, service_role;
grant all on all tables in schema {svc} to authenticated, service_role;
grant all on all sequences in schema {svc} to authenticated, service_role;
grant execute on all functions in schema {svc} to authenticated, service_role;
"""
open(out, "w", encoding="utf8").write(body)
print(out, len(body.splitlines()), "lines")
